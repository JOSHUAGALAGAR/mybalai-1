-- ============================================================
-- 0020_landlord_applications
-- ============================================================
-- Landlord accounts are created by the superadmin. A property owner who wants to list a property
-- applies from the public landing page (/apply); the superadmin reviews the application and, on
-- approval, the landlord account is created.
--
-- Only the server (service role) touches this table: RLS is on and there is no policy.
-- One PENDING application per email (a second one is refused until the first is decided).
--
-- Idempotent — safe to re-run. Apply in the Supabase SQL editor.
-- ============================================================

begin;

create table if not exists public.landlord_applications (
  application_id bigint generated by default as identity primary key,
  full_name      text not null check (length(btrim(full_name)) between 2 and 120),
  email          text not null check (length(email) between 5 and 200),
  phone          text not null check (length(phone) between 6 and 40),
  business_name  text check (business_name is null or length(business_name) <= 160),
  property_name  text not null check (length(btrim(property_name)) between 2 and 200),
  address        text not null check (length(btrim(address)) between 5 and 300),
  rooms_count    integer not null check (rooms_count between 1 and 1000),
  description    text check (description is null or length(description) <= 2000),
  status         text not null default 'pending' check (status in ('pending', 'approved', 'rejected')),
  reject_reason  text,
  reviewed_by    bigint references public.user_accounts (legacy_user_id) on delete set null,
  reviewed_at    timestamptz,
  landlord_id    bigint references public.user_accounts (legacy_user_id) on delete set null,
  created_at     timestamptz not null default now(),
  constraint landlord_applications_rejected_has_reason
    check (status <> 'rejected' or (reject_reason is not null and length(btrim(reject_reason)) > 0))
);

create unique index if not exists landlord_applications_one_pending_per_email
  on public.landlord_applications (lower(email)) where status = 'pending';
create index if not exists landlord_applications_queue_idx
  on public.landlord_applications (status, created_at desc);

alter table public.landlord_applications enable row level security;

commit;

