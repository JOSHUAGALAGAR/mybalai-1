-- ============================================================
-- 0021_application_documents
-- ============================================================
-- A property owner applying to list (0020) attaches their business documents: Mayor's / business
-- permit, Barangay permit, DTI (or SEC / CDA) registration, proof of ownership, a valid ID, and
-- optionally BIR registration, fire-safety and sanitary permits.
--
-- The files live in a PRIVATE `application-documents` bucket: no public URL exists. Applicants
-- upload with short-lived signed upload URLs the server issues (so no Storage policy is needed),
-- and only a superadmin is ever handed a link to view one (it expires after a minute).
--
-- Idempotent — safe to re-run. Apply in the Supabase SQL editor (after 0020).
-- ============================================================

begin;

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values (
  'application-documents', 'application-documents', false, 5242880,
  array['image/jpeg', 'image/png', 'image/webp', 'application/pdf']
)
on conflict (id) do update
  set public = false,                        -- must never become public
      file_size_limit = 5242880,
      allowed_mime_types = array['image/jpeg', 'image/png', 'image/webp', 'application/pdf'];

create table if not exists public.landlord_application_documents (
  document_id    bigint generated by default as identity primary key,
  application_id bigint not null references public.landlord_applications (application_id) on delete cascade,
  doc_type       text not null check (doc_type in (
                   'mayors_permit', 'barangay_permit', 'dti_registration', 'proof_ownership', 'valid_id',
                   'bir_registration', 'fire_safety', 'sanitary_permit', 'other'
                 )),
  storage_path   text not null unique,
  file_name      text not null check (length(file_name) <= 300),
  mime_type      text not null,
  size_bytes     integer not null check (size_bytes > 0),
  created_at     timestamptz not null default now()
);

create index if not exists landlord_application_documents_app_idx
  on public.landlord_application_documents (application_id);

alter table public.landlord_application_documents enable row level security;

commit;

