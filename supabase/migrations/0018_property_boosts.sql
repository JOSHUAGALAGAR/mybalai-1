-- ============================================================
-- 0018_property_boosts
-- ============================================================
-- MyBalai has no subscriptions: listing is free, MyBalai earns a transaction fee on online
-- payments (0017) and, optionally, from BOOSTS — a landlord pays to have one property shown first
-- in search for a number of days.
--
-- 1. boost_packages: what a boost costs (name, days, price). Edited by the superadmin.
-- 2. property_boosts (baseline table, coin-based and empty) gets what a PayMongo purchase needs:
--    package, days, amount, status (pending -> active -> expired | cancelled), the PayMongo
--    session / payment ids, and the PayMongo fee MyBalai paid on it.
-- 3. settle_property_boost(): idempotently activates a paid boost. A boost bought while another is
--    still running starts when that one ends, so days are never lost or overlapped.
--
-- Idempotent — safe to re-run. Apply in the Supabase SQL editor.
-- ============================================================

begin;

create table if not exists public.boost_packages (
  package_id bigint generated by default as identity primary key,
  name       text not null check (length(btrim(name)) between 2 and 80),
  days       integer not null check (days between 1 and 365),
  price      numeric(12, 2) not null check (price >= 20),   -- PayMongo's minimum charge is ₱20
  is_active  boolean not null default true,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
alter table public.boost_packages enable row level security;

insert into public.boost_packages (name, days, price, sort_order)
select v.name, v.days, v.price, v.sort_order
from (values ('7 days', 7, 99.00, 1), ('14 days', 14, 179.00, 2), ('30 days', 30, 299.00, 3))
  as v(name, days, price, sort_order)
where not exists (select 1 from public.boost_packages);

alter table public.property_boosts
  add column if not exists package_id bigint references public.boost_packages (package_id) on delete set null,
  add column if not exists days integer,
  add column if not exists amount numeric(12, 2) not null default 0,
  add column if not exists processing_fee_amount numeric(12, 2) not null default 0,
  add column if not exists status text not null default 'pending',
  add column if not exists paymongo_session_id text,
  add column if not exists paymongo_payment_id text,
  add column if not exists paid_at timestamptz,
  add column if not exists updated_at timestamptz not null default now();

-- replace any old status CHECK with the app's
do $$
declare r record;
begin
  for r in
    select c.conname from pg_constraint c
    where c.contype = 'c' and c.conrelid = 'public.property_boosts'::regclass
      and pg_get_constraintdef(c.oid) ~* 'status'
  loop
    execute format('alter table public.property_boosts drop constraint %I', r.conname);
  end loop;
end $$;
alter table public.property_boosts
  add constraint property_boosts_status_check
  check (status in ('pending', 'active', 'expired', 'cancelled'));

create index if not exists property_boosts_live_idx
  on public.property_boosts (status, ends_at);
create index if not exists property_boosts_property_idx
  on public.property_boosts (property_id, created_at desc);
create unique index if not exists property_boosts_session_key
  on public.property_boosts (paymongo_session_id) where paymongo_session_id is not null;

create or replace function public.settle_property_boost(p_boost bigint, p_paymongo_payment_id text)
returns text
language plpgsql security definer set search_path = public as $$
declare
  b        public.property_boosts%rowtype;
  v_start  timestamptz;
  v_rate   numeric;
begin
  select * into b from property_boosts where boost_id = p_boost for update;
  if not found then return 'not_found'; end if;
  if b.status = 'active' or b.status = 'expired' then return 'already_settled'; end if;

  -- start after any boost of this property that is still running
  select greatest(now(), coalesce(max(ends_at), now())) into v_start
  from property_boosts
  where property_id = b.property_id and status = 'active' and ends_at > now() and boost_id <> b.boost_id;

  select coalesce(paymongo_fee_rate, 0) into v_rate
  from platform_fee_settings where is_active order by fee_setting_id desc limit 1;

  update property_boosts
  set status = 'active',
      is_active = true,
      starts_at = v_start,
      ends_at = v_start + make_interval(days => coalesce(b.days, 0)),
      paid_at = now(),
      paymongo_payment_id = coalesce(p_paymongo_payment_id, b.paymongo_payment_id),
      processing_fee_amount = round(b.amount * coalesce(v_rate, 0) / 100, 2),
      updated_at = now()
  where boost_id = p_boost;
  return 'settled';
end
$$;
revoke all on function public.settle_property_boost(bigint, text) from public;
grant execute on function public.settle_property_boost(bigint, text) to service_role;

commit;

