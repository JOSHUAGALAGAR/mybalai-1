-- ============================================================
-- 0022_tenant_preferences_and_matching
-- ============================================================
-- Intelligent tenant matching: a tenant tells MyBalai what they are looking for (budget, area,
-- amenities, kind of room, a few lifestyle answers) and gets listings ranked by how well they fit.
--
-- 1. tenant_preferences: one row per tenant. The lifestyle answers are OPT-IN: they are kept for
--    landlord-side room allocation only when `share_lifestyle` is true.
-- 2. match_logs: which listings were recommended to whom, at what rank and score. This is the
--    evaluation record (were recommendations booked? did fit predict stays and reviews?).
--
-- Only the server (service role) touches these tables: RLS on, no policies. Idempotent.
-- ============================================================

begin;

create table if not exists public.tenant_preferences (
  legacy_user_id  bigint primary key references public.user_accounts (legacy_user_id) on delete cascade,
  budget_min      numeric(12, 2) check (budget_min is null or budget_min >= 0),
  budget_max      numeric(12, 2) check (budget_max is null or budget_max >= 0),
  area_label      text check (area_label is null or length(area_label) <= 300),
  area_lat        double precision check (area_lat is null or area_lat between -90 and 90),
  area_lng        double precision check (area_lng is null or area_lng between -180 and 180),
  max_distance_km numeric(5, 1) not null default 3 check (max_distance_km between 0.5 and 100),
  amenity_ids     integer[] not null default '{}',
  room_kind       text not null default 'any' check (room_kind in ('any', 'solo', 'shared')),
  move_in         text not null default 'flexible' check (move_in in ('this_month', 'next_month', 'flexible')),
  occupation      text check (occupation is null or occupation in ('student', 'working', 'other')),
  schedule        text check (schedule is null or schedule in ('day', 'night', 'mixed')),
  noise           text check (noise is null or noise in ('quiet', 'balanced', 'social')),
  share_lifestyle boolean not null default false,
  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now(),
  constraint tenant_preferences_budget_order check (budget_min is null or budget_max is null or budget_min <= budget_max),
  constraint tenant_preferences_area_pair check ((area_lat is null) = (area_lng is null))
);
alter table public.tenant_preferences enable row level security;

create table if not exists public.match_logs (
  log_id      bigint generated by default as identity primary key,
  user_id     bigint not null references public.user_accounts (legacy_user_id) on delete cascade,
  property_id bigint not null references public.properties (property_id) on delete cascade,
  rank        integer not null check (rank >= 1),
  score       numeric(5, 2) not null check (score between 0 and 100),
  created_at  timestamptz not null default now()
);
create index if not exists match_logs_user_idx on public.match_logs (user_id, created_at desc);
create index if not exists match_logs_property_idx on public.match_logs (property_id, created_at desc);
alter table public.match_logs enable row level security;

commit;

