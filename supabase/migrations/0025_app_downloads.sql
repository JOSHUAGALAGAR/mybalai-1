-- ============================================================
-- 0025_app_downloads
-- ============================================================
-- Counts downloads of the Android app from the landing page (/download/android).
-- One row per download, with only the time and platform: no IP address, no user agent, no account.
-- Only the server (service role) reads or writes it: RLS on, no policies. Idempotent.
-- ============================================================

begin;

create table if not exists public.app_downloads (
  download_id bigint generated by default as identity primary key,
  platform    text not null default 'android' check (platform in ('android')),
  created_at  timestamptz not null default now()
);
create index if not exists app_downloads_created_idx on public.app_downloads (created_at desc);
alter table public.app_downloads enable row level security;

commit;

