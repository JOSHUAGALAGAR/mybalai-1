-- ============================================================
-- 0015_profile_photos_and_id_verification
-- ============================================================
-- 1. Profile photos: a PUBLIC `profile-images` Storage bucket (avatars are shown to other users).
-- 2. Tenant ID verification: tenants upload the FRONT and BACK of a government ID; a superadmin
--    reviews it. Stored in a PRIVATE `id-documents` bucket — no public URL exists, and nothing but
--    the server (service role) can read or write it. The admin sees the pictures through links that
--    expire after a minute. `identity_verifications` keeps one row per submission
--    (pending -> approved | rejected). A rejected tenant may submit again; at most ONE submission
--    can be pending per tenant. `user_accounts.id_verified_at` mirrors "approved" so the app can
--    show the Verified badge without joining.
--
-- Uploads go browser/phone -> Storage through short-lived signed upload URLs that the server issues
-- only after checking who is asking, so NO Storage policies are needed for either bucket.
--
-- Idempotent — safe to re-run. Apply in the Supabase SQL editor.
-- ============================================================

begin;

-- ---- buckets --------------------------------------------------------------------
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values (
  'profile-images', 'profile-images', true, 3145728,
  array['image/jpeg', 'image/png', 'image/webp']
)
on conflict (id) do update
  set public = true,
      file_size_limit = 3145728,
      allowed_mime_types = array['image/jpeg', 'image/png', 'image/webp'];

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values (
  'id-documents', 'id-documents', false, 8388608,
  array['image/jpeg', 'image/png', 'image/webp']
)
on conflict (id) do update
  set public = false,                       -- must never become public
      file_size_limit = 8388608,
      allowed_mime_types = array['image/jpeg', 'image/png', 'image/webp'];

-- ---- verification submissions ----------------------------------------------------
create table if not exists public.identity_verifications (
  verification_id bigint generated by default as identity primary key,
  user_id         bigint not null references public.user_accounts (legacy_user_id) on delete cascade,
  id_type         text   not null check (id_type in (
                    'philsys', 'drivers_license', 'passport', 'umid', 'prc', 'postal',
                    'voters', 'sss', 'tin', 'philhealth'
                  )),
  front_path      text   not null,
  back_path       text   not null,
  status          text   not null default 'pending' check (status in ('pending', 'approved', 'rejected')),
  reject_reason   text,
  submitted_at    timestamptz not null default now(),
  reviewed_by     bigint references public.user_accounts (legacy_user_id),
  reviewed_at     timestamptz,
  constraint identity_verifications_distinct_files check (front_path <> back_path),
  constraint identity_verifications_rejected_has_reason
    check (status <> 'rejected' or (reject_reason is not null and length(btrim(reject_reason)) > 0))
);

-- one waiting submission per tenant; a file belongs to one submission
create unique index if not exists identity_verifications_one_pending
  on public.identity_verifications (user_id) where status = 'pending';
create unique index if not exists identity_verifications_front_key on public.identity_verifications (front_path);
create unique index if not exists identity_verifications_back_key  on public.identity_verifications (back_path);
create index if not exists identity_verifications_user_idx
  on public.identity_verifications (user_id, submitted_at desc);
create index if not exists identity_verifications_queue_idx
  on public.identity_verifications (status, submitted_at);

-- only the service layer touches this table
alter table public.identity_verifications enable row level security;

-- ---- the badge ---------------------------------------------------------------------
alter table public.user_accounts add column if not exists id_verified_at timestamptz;

commit;

